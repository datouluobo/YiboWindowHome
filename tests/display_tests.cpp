#include "state.h"
#include <algorithm>
#include <iostream>
#include <cmath>

int main() {
    int failures{};auto check=[&](bool ok,const char* label){std::cout<<(ok?"PASS ":"FAIL ")<<label<<'\n';if(!ok)++failures;};
    home::Display left{L"DISPLAY1",L"panel-a",{0,0,1920,1080},{0,0,1920,1040},96,true};
    home::Display right{L"DISPLAY2",L"panel-b",{1920,0,3840,1080},{1920,0,3840,1040},96,false};
    std::vector<home::Display> screens{left,right};
    home::Record saved;saved.normal={1600,120,2500,720};saved.actual=saved.normal;
    saved.work=right.work;saved.monitor=right.monitor;saved.dpi=96;saved.device=right.device;saved.displayIdentity=right.identity;saved.topology=screens;
    RECT current{100,100,900,700};
    auto p=home::planRestore(saved,screens,current);
    check(p&&!p->environmentChanged&&!p->fallback&&EqualRect(&p->normal,&saved.normal),"unchanged complete topology preserves exact cross-screen rectangle");
    auto reordered=screens;std::reverse(reordered.begin(),reordered.end());
    check(home::sameTopology(screens,reordered),"display enumeration order does not change topology");
    reordered[0].device=L"DISPLAY7";reordered[1].device=L"DISPLAY9";
    p=home::planRestore(saved,reordered,current);
    check(p&&!p->environmentChanged&&p->displayIndex==0&&EqualRect(&p->normal,&saved.normal),"stable device identity survives DISPLAY renumbering");
    auto moved=screens;moved[1].monitor={-1920,0,0,1080};moved[1].work={-1920,0,0,1040};
    p=home::planRestore(saved,moved,current);
    check(p&&p->environmentChanged&&p->crossScreenReduced&&p->displayIndex==1&&p->normal.left>=-1920&&p->normal.right<=0,"rearranged original screen retains identity and contains prior cross-screen window");
    auto changedOther=screens;changedOther[0].dpi=144;
    p=home::planRestore(saved,changedOther,current);
    check(p&&p->environmentChanged&&p->crossScreenReduced&&p->normal.left>=1920,"a change on another screen invalidates complete-topology equality");
    auto replaced=screens;replaced[1].identity=L"different-panel";
    p=home::planRestore(saved,replaced,current);
    check(p&&p->fallback&&p->displayIndex==0&&p->normal.right<=1920,"reused DISPLAY number does not match a disconnected physical panel");
    auto duplicate=screens;duplicate[0].identity=right.identity;
    p=home::planRestore(saved,duplicate,current);
    check(p&&p->fallback&&p->displayIndex==0,"ambiguous duplicate identity falls back to current screen");
    auto removed=std::vector<home::Display>{left};
    p=home::planRestore(saved,removed,current);
    check(p&&p->fallback&&p->normal.left>=0&&p->normal.right<=1920,"disconnected anchor maps into remaining screen");
    p=home::planRestore(saved,replaced,{2100,100,2900,600});
    check(p&&p->fallback&&p->displayIndex==1,"fallback uses target window's current screen before primary");
    p=home::planRestore(saved,replaced,{});
    check(p&&p->displayIndex==0,"unavailable target bounds fall back to primary screen");
    check(!home::planRestore(saved,{},current),"no active displays prevents restoration");
    check(home::displayForRect({1800,50,2300,500},screens)==std::optional<size_t>(1),"anchor follows largest overlap");
    check(home::displayForRect({4000,100,4300,500},screens)==std::optional<size_t>(1),"off-screen target selects nearest screen");
    home::Record ordinary=saved;ordinary.normal={240,140,1200,740};ordinary.actual=ordinary.normal;
    ordinary.work=left.work;ordinary.monitor=left.monitor;ordinary.device=left.device;ordinary.displayIdentity=left.identity;
    auto scaled=screens;scaled[0].dpi=144;scaled[0].monitor={0,0,2880,1620};scaled[0].work={0,0,2880,1560};
    p=home::planRestore(ordinary,scaled,current);
    check(p&&p->normal.right-p->normal.left==1440&&p->normal.bottom-p->normal.top==900&&p->normal.left==360&&p->normal.top==210,"DPI change preserves DIP size and relative movable-space position");
    auto taskbar=screens;taskbar[0].work={0,80,1920,1080};
    p=home::planRestore(ordinary,taskbar,current);
    check(p&&p->environmentChanged&&p->normal.top>=80&&p->normal.bottom<=1080,"top taskbar changes work-area mapping");
    auto reduced=screens;reduced[0].monitor={0,0,800,600};reduced[0].work={0,0,800,560};
    p=home::planRestore(ordinary,reduced,current);
    check(p&&p->normal.right-p->normal.left==800&&p->normal.bottom-p->normal.top==560,"oversized geometry shrinks to changed work area");
    auto partial=ordinary;partial.normal={-400,100,500,700};
    p=home::planRestore(partial,screens,current);
    check(p&&!p->visibilityCorrected&&EqualRect(&p->normal,&partial.normal),"same environment preserves usable partially off-screen placement");
    auto unreachable=ordinary;unreachable.normal={200,-600,1000,-100};
    p=home::planRestore(unreachable,screens,current);
    check(p&&p->visibilityCorrected&&p->normal.top==0&&p->normal.bottom-p->normal.top==500,"inaccessible caption gets minimum positional correction without resizing");
    auto gap=screens;gap[1].monitor={3000,0,4920,1080};gap[1].work={3000,0,4920,1040};
    check(!home::hasReachableCaption({2100,100,2800,700},gap),"virtual desktop bounding box does not make monitor gap reachable");
    auto gapRecord=ordinary;gapRecord.normal={2100,100,2800,700};gapRecord.topology=gap;
    p=home::planRestore(gapRecord,gap,current);
    check(p&&p->visibilityCorrected&&home::hasReachableCaption(p->normal,gap),"same-environment window in monitor gap is brought to a real screen");
    auto legacy=ordinary;legacy.topology.clear();legacy.displayIdentity.clear();
    p=home::planRestore(legacy,screens,current);
    check(p&&p->environmentChanged&&!p->fallback&&EqualRect(&p->normal,&legacy.normal),"legacy record retains usable same-screen placement through conservative mapping");
    auto primary=screens;primary[0].primary=false;primary[1].primary=true;
    check(!home::sameTopology(screens,primary),"primary-screen change is part of topology");
    auto uncertain=screens;uncertain[0].identity.clear();uncertain[1].identity.clear();
    check(home::sameTopology(uncertain,uncertain)&&!home::sameTopology(uncertain,screens),"identity availability changes trigger conservative remapping");
    auto invalid=ordinary;invalid.dpi=0;
    check(!home::planRestore(invalid,screens,current),"invalid saved DPI cannot enter conversion");
    RECT canvas{20,30,980,570};
    auto preview=home::buildDesktopPreview(&saved,screens,current,canvas);
    check(preview&&preview->displays.size()==2&&preview->window&&preview->plan&&EqualRect(&preview->windowBounds,&saved.normal),"desktop preview uses the same restore plan and all connected views");
    check(preview&&std::abs(preview->displays[1].monitor.left-preview->displays[0].monitor.right)<0.001&&std::abs(preview->scale-0.25)<0.001,"uniform fitting preserves real monitor adjacency and aspect ratio");
    auto vertical=screens;vertical[1].monitor={-1080,-1920,0,0};vertical[1].work={-1080,-1920,0,-40};
    preview=home::buildDesktopPreview(nullptr,vertical,current,canvas);
    check(preview&&preview->displays.size()==2&&preview->desktopBounds.left==-1080&&preview->desktopBounds.top==-1920&&preview->displays[1].monitor.bottom<=preview->displays[0].monitor.top&&!preview->window,"negative coordinates and portrait monitor above-left are represented without a fabricated record");
    auto singlePreview=home::buildDesktopPreview(&saved,removed,current,canvas);auto singlePlan=home::planRestore(saved,removed,current);
    check(singlePreview&&singlePreview->displays.size()==1&&singlePreview->plan->fallback&&EqualRect(&singlePreview->windowBounds,&singlePlan->normal),"disconnecting a display rebuilds a one-monitor preview using real fallback geometry");
    auto maximal=ordinary;maximal.maximized=true;
    preview=home::buildDesktopPreview(&maximal,taskbar,current,canvas);
    check(preview&&EqualRect(&preview->windowBounds,&taskbar[preview->plan->displayIndex].work),"maximized record preview uses current work area including taskbar offset");
    check(!home::buildDesktopPreview(&saved,{},current,canvas)&&!home::buildDesktopPreview(&saved,screens,current,{0,0,0,0}),"missing monitors and empty viewport fail explicitly");
    auto snapshot=home::collectDisplays();
    check(!snapshot.empty()&&snapshot.size()<=64,"live read-only desktop enumeration returns a bounded snapshot");
    auto livePreview=home::currentDesktopPreview(nullptr,current,canvas);std::vector<home::Display> previewDisplays;
    if(livePreview)for(auto& view:livePreview->displays)previewDisplays.push_back(view.display);
    check(livePreview&&home::sameTopology(snapshot,previewDisplays),"live desktop preview enumerates actual connected display count, arrangement and DPI");
    size_t identities{};for(auto& d:snapshot)if(!d.identity.empty())++identities;
    std::cout<<"Active desktop views: "<<snapshot.size()<<"; with physical identity: "<<identities<<'\n';
    std::cout<<"Failures: "<<failures<<'\n';return failures?1:0;
}
